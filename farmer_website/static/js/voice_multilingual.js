    setLanguage(langCode) {
        this.currentLang = langCode;
        localStorage.setItem('app_language', langCode);
        this.applyLanguage(langCode);
    }

    applyLanguage(langCode) {
        const sel = document.getElementById('globalLanguageSelect');
        if (sel) sel.value = langCode;
        this.translateDOMTree(document.body, langCode);
    }

    translateDOMTree(rootNode, langCode) {
        if (!rootNode) return;

        // 1. Text node translation via TreeWalker
        const walker = document.createTreeWalker(
            rootNode,
            NodeFilter.SHOW_TEXT,
            {
                acceptNode: (node) => {
                    const parentTag = node.parentElement ? node.parentElement.tagName.toLowerCase() : '';
                    if (['script', 'style', 'noscript', 'textarea'].includes(parentTag)) {
                        return NodeFilter.FILTER_REJECT;
                    }
                    if (node.parentElement && node.parentElement.classList && node.parentElement.classList.contains('no-translate')) {
                        return NodeFilter.FILTER_REJECT;
                    }
                    const text = node.nodeValue ? node.nodeValue.trim() : '';
                    return text.length > 0 ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP;
                }
            }
        );

        let node;
        while ((node = walker.nextNode())) {
            let original = this.originalNodes.get(node);
            if (!original) {
                original = node.nodeValue;
                this.originalNodes.set(node, original);
            }

            if (langCode === 'en') {
                node.nodeValue = original;
            } else {
                const trimmed = original.trim();
                if (DICTIONARY[trimmed] && DICTIONARY[trimmed][langCode]) {
                    const translated = DICTIONARY[trimmed][langCode];
                    node.nodeValue = original.replace(trimmed, translated);
                } else {
                    let modified = original;
                    for (const enKey of this.sortedKeys) {
                        const transObj = DICTIONARY[enKey];
                        if (transObj && transObj[langCode] && modified.includes(enKey)) {
                            modified = modified.split(enKey).join(transObj[langCode]);
                        }
                    }
                    node.nodeValue = modified;
                }
            }
        }

        // 2. Select Option Texts translation (Preserve option values!)
        document.querySelectorAll('select').forEach(select => {
            if (select.id === 'globalLanguageSelect') return;
            select.querySelectorAll('option').forEach(opt => {
                let orig = opt.getAttribute('data-orig-text');
                if (!orig) {
                    orig = opt.text;
                    opt.setAttribute('data-orig-text', orig);
                }
                if (langCode === 'en') {
                    opt.text = orig;
                } else if (DICTIONARY[orig] && DICTIONARY[orig][langCode]) {
                    opt.text = DICTIONARY[orig][langCode];
                } else {
                    let mod = orig;
                    for (const enKey of this.sortedKeys) {
                        const transObj = DICTIONARY[enKey];
                        if (transObj && transObj[langCode] && mod.includes(enKey)) {
                            mod = mod.split(enKey).join(transObj[langCode]);
                        }
                    }
                    opt.text = mod;
                }
            });
        });

        // 3. Input Placeholders translation
        document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
            let orig = el.getAttribute('data-orig-placeholder');
            if (!orig) {
                orig = el.placeholder;
                el.setAttribute('data-orig-placeholder', orig);
            }
            if (langCode === 'en') {
                el.placeholder = orig;
            } else if (DICTIONARY[orig] && DICTIONARY[orig][langCode]) {
                el.placeholder = DICTIONARY[orig][langCode];
            } else {
                let mod = orig;
                for (const enKey of this.sortedKeys) {
                    const transObj = DICTIONARY[enKey];
                    if (transObj && transObj[langCode] && mod.includes(enKey)) {
                        mod = mod.split(enKey).join(transObj[langCode]);
                    }
                }
                el.placeholder = mod;
            }
        });
    }

    observeDOMMutations() {
        const observer = new MutationObserver((mutations) => {
            if (this.currentLang !== 'en') {
                mutations.forEach(mutation => {
                    mutation.addedNodes.forEach(node => {
                        if (node.nodeType === Node.ELEMENT_NODE) {
                            this.translateDOMTree(node, this.currentLang);
                        }
                    });
                });
            }
        });

        observer.observe(document.body, { childList: true, subtree: true });
    }

